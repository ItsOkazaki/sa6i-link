# Make a desktop shortcut that starts Sa6i Link without a console window.
#
# The application does not run from a double-click: it needs a data directory
# and a few settings, which the batch file supplies. Rebuilding the application
# to default those is out of reach here, so this creates a launcher that runs
# exactly the same batch file - with no window at all - and a shortcut to it
# wearing the application's icon.
#
# Put this file and "Make Sa6i Link Shortcut.cmd" in the candidate folder (the
# one holding the Sa6i Link executable and its Start ... .cmd), then run the
# .cmd.

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$log = Join-Path $here 'shortcut-log.txt'

function Say([string] $text) {
    Write-Host $text
    Add-Content -Path $log -Value $text
}

try {
    Set-Content -Path $log -Value ('Sa6i Link shortcut log ' + (Get-Date).ToString('s'))
    Say 'Sa6i Link: make a shortcut that works'
    Say ''
    Say ('Folder: ' + $here)
    Say ''

    # The batch file that starts the application, here or one level up.
    $batch = $null
    foreach ($folder in @($here, (Split-Path -Parent $here))) {
        if ($batch -ne $null) { break }
        foreach ($file in (Get-ChildItem -LiteralPath $folder -Force | Where-Object {
                    (-not $_.PSIsContainer) -and ($_.Extension -eq '.cmd') -and ($_.Name -like 'Start*')
                })) {
            if ($batch -eq $null) { $batch = $file }
        }
    }
    if ($batch -eq $null) {
        throw 'No "Start ... .cmd" was found here or one folder up. Put this file beside the batch file that starts Sa6i Link.'
    }
    Say ('Batch file: ' + $batch.FullName)
    Say ''
    Say 'What it does, so this is answerable from the log:'
    foreach ($line in [System.IO.File]::ReadAllLines($batch.FullName)) {
        Say ('  | ' + $line)
    }
    Say ''

    # The application icon comes from the executable.
    $exe = $null
    foreach ($file in (Get-ChildItem -LiteralPath $here -Force | Where-Object {
                (-not $_.PSIsContainer) -and ($_.Extension -eq '.exe') -and ($_.Length -gt 1048576)
            })) {
        if ($exe -eq $null) { $exe = $file }
    }
    if ($exe -ne $null) { Say ('Icon from: ' + $exe.Name) }

    # A launcher with no window of its own: it runs the batch file hidden, so
    # the settings and arguments the application needs still come from the one
    # place they are defined.
    $launcher = Join-Path $here 'Sa6i Link (hidden).vbs'
    $vbs = @()
    $vbs += "' Starts Sa6i Link with no console window."
    $vbs += "' Generated by Make-Sa6i-Link-Shortcut.ps1; it only runs the batch file."
    $vbs += 'Set shell = CreateObject("WScript.Shell")'
    $vbs += 'shell.Run Chr(34) & "' + $batch.FullName + '" & Chr(34), 0, False'
    [System.IO.File]::WriteAllLines($launcher, $vbs)
    Say ('Wrote ' + $launcher)

    $wscript = Join-Path $env:SystemRoot 'System32\wscript.exe'
    if (-not (Test-Path -LiteralPath $wscript)) { throw ('wscript.exe was not found at ' + $wscript) }

    $shell = New-Object -ComObject WScript.Shell
    $desktop = [Environment]::GetFolderPath('Desktop')
    $places = @($desktop, $here)
    $made = 0
    foreach ($place in $places) {
        if ([string]::IsNullOrEmpty($place)) { continue }
        $path = Join-Path $place 'Sa6i Link.lnk'
        if ((Test-Path -LiteralPath $path) -and ($place -eq $here)) { continue }
        $shortcut = $shell.CreateShortcut($path)
        $shortcut.TargetPath = $wscript
        $shortcut.Arguments = '"' + $launcher + '"'
        $shortcut.WorkingDirectory = $batch.DirectoryName
        if ($exe -ne $null) { $shortcut.IconLocation = $exe.FullName + ',0' }
        $shortcut.WindowStyle = 1
        $shortcut.Description = 'Sa6i Link'
        $shortcut.Save()
        Say ('Created ' + $path)
        $made = $made + 1
    }
    [void][System.Runtime.InteropServices.Marshal]::ReleaseComObject($shell)

    Say ''
    if ($made -eq 0) { throw 'No shortcut could be created.' }
    Say 'Done. "Sa6i Link" on the Desktop starts the application with no window.'
    Say 'Right-click it to pin it to the taskbar or the Start menu.'
} catch {
    Say ''
    Say ('ERROR: ' + $_.Exception.Message)
    exit 1
}
