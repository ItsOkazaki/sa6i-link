#!/usr/bin/env python3
"""Generate docs/plan/M2-FIXTURES.md from the rule files and the fixtures.

    python3 scripts/fixtures-report.py           # write the page
    python3 scripts/fixtures-report.py --check   # exit 1 if it is out of date

The fixtures are the source of truth: each one is a machine behaviour and the
findings it must produce, and `tests/scenarios.rs` holds the harness that believes
it. This page is the same information arranged so a person can read it - what each
rule is, which number it decides with, which fixture proves it fires, and which one
proves it can stay quiet.

Nothing here compiles Rust or reads Windows. It is a re-arrangement of two
directories, and `--check` is the only thing standing between the page and a lie.
"""

import json
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
INTEL = ROOT / "core/sa6i-link-intel"
RULES = INTEL / "rules"
FIXTURES = INTEL / "tests/scenarios"
OUT = ROOT / "docs/plan/M2-FIXTURES.md"

# The order a rule's numbers are described in, and how to say each one. A key that
# is not here is still printed - a silent omission is how a page goes stale.
UNITS = {
    "warn_percent": "%",
    "critical_percent": "%",
    "total_below_percent": "%",
    "growth_mb": " MiB of growth",
    "fill_mb": " MiB lost",
    "slow_ms": " ms per transfer",
    "pages_per_second": "/s",
}
IDENTITY = {"id", "severity", "confidence", "requires", "firing", "near_miss"}


def numbers(entry):
    """The rule's own keys, in a stable order, as `key = value` pairs."""
    parts = []
    for key in sorted(entry):
        if key in IDENTITY:
            continue
        value = entry[key]
        parts.append(f"{key} = {value}{UNITS.get(key, '')}")
    return parts


def rules():
    """Every rule file, by rule id."""
    found = {}
    for path in sorted(RULES.glob("*.toml")):
        for entry in tomllib.loads(path.read_text()).get("rule", []):
            found[entry["id"]] = (path.name, entry)
    return found


def fixtures():
    """Every fixture, by file name, with its name, minutes and verdicts."""
    found = {}
    for path in sorted(FIXTURES.glob("*.json")):
        data = json.loads(path.read_text())
        minutes = sum(segment["minutes"] for segment in data["segments"])
        fires = [item["rule"] for item in data.get("expect", [])]
        quiet = list(data.get("quiets", []))
        found[path.name] = {
            "name": data["name"],
            "about": data["about"],
            "minutes": minutes,
            "fires": fires,
            "quiet": quiet,
        }
    return found


def by_name(found, name):
    for path, fixture in found.items():
        if fixture["name"] == name:
            return path, fixture
    return None, None


def render():
    rule_table = rules()
    all_fixtures = fixtures()
    lines = []
    add = lines.append

    add("# M2's fixtures, generated")
    add("")
    add("> Generated by `scripts/fixtures-report.py` from `core/sa6i-link-intel/rules/*.toml`")
    add("> and `core/sa6i-link-intel/tests/scenarios/*.json`. Do not edit by hand: run the")
    add("> script, and `--check` proves the page still matches the two directories.")
    add("")
    add(
        f"{len(rule_table)} rules, {len(all_fixtures)} fixtures, "
        f"{sum(len(numbers(entry)) for _, entry in rule_table.values())} numbers."
    )
    add("")
    add("A fixture is a machine behaviour and the findings it must produce, written down")
    add("as one file so a reviewer reads the claim and the result together. Every rule")
    add("ships **a firing case and a near-miss** — a rule nobody can make silent is a rule")
    add("that pages people for nothing — and `tests/scenarios.rs` fails the build if one")
    add("is missing.")
    add("")

    add("## The rules, and the fixtures that prove them")
    add("")
    add("| rule | severity | numbers | fires in | stays quiet in |")
    add("| --- | --- | --- | --- | --- |")
    for rule_id in sorted(rule_table):
        _, entry = rule_table[rule_id]
        firing = entry.get("firing", "—")
        near = entry.get("near_miss", "—")
        numbers_text = "; ".join(f"`{part}`" for part in numbers(entry)) or "none"
        add(f"| `{rule_id}` | {entry.get('severity', '?')} | {numbers_text} | `{firing}` | `{near}` |")
    add("")

    add("## Every fixture")
    add("")
    add("Minutes is how much history the fixture gives the rules to look at, which is")
    add("why it matters: eleven of the twelve rules cannot answer a question about a")
    add("window shorter than their own, and `system.long_uptime` is the exception.")
    add("")
    add("| file | minutes | fires | stays quiet |")
    add("| --- | --- | --- | --- |")
    for path in sorted(all_fixtures):
        fixture = all_fixtures[path]
        fires = ", ".join(f"`{rule}`" for rule in fixture["fires"]) or "—"
        quiet = ", ".join(f"`{rule}`" for rule in fixture["quiet"]) or "—"
        add(f"| `{path}` | {fixture['minutes']} | {fires} | {quiet} |")
    add("")

    add("## What each fixture describes")
    add("")
    add("The sentence below each name is the fixture's own `about` field, quoted, so")
    add("the page cannot describe a fixture differently from the file it came from.")
    add("")
    for path in sorted(all_fixtures):
        fixture = all_fixtures[path]
        add(f"**`{fixture['name']}`** — {fixture['about']}")
        add("")

    add("## What these fixtures do not prove")
    add("")
    add("They are recipes, not captures. Each segment says \"ten minutes at 92 %\" and the")
    add("harness expands it to a 1 Hz sample series, which is what the collector *would*")
    add("have produced — but no Windows counter produced it. Nothing here has been")
    add("compared with Task Manager, and nothing here has been through a compiler.")
    add("")
    add("Two things follow, both recorded in [`M2-VERIFY.md`](M2-VERIFY.md):")
    add("")
    add("- The fixture count is not coverage. A rule can pass every fixture and still be")
    add("  wrong about a real machine, which is what the five-machine review is for.")
    add("- `gpu.vram_pressure` cannot be provoked on Windows 7 at all, because the counter")
    add("  set does not exist there. `integrated-gpu-reports-no-limit` is as close as the")
    add("  old machine gets: it proves the silence, not the firing.")
    add("")
    return "\n".join(lines)


def main(argv):
    text = render()
    if "--check" in argv:
        if not OUT.exists():
            print(f"{OUT.relative_to(ROOT)} does not exist; run without --check", file=sys.stderr)
            return 1
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run again", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
